export const itemById = Object.fromEntries(ITEMS.map((i) => [i.id, i]));

/**
 * המאגר לפי רמה: 'kids' – רק פריטים לקטנים; 'all' – כל הפריטים הרגילים; 'hard' – רק חבילת "🦉 מאתגר".
 * 'self' (השומר בוחר בעצמו) – בלי מאגר.
 */
export const itemPool = (level) => {
  if (level === 'kids') return ITEMS.filter((i) => i.kids);
  if (level === 'hard') return ITEMS.filter((i) => i.pack === 'hard');
  if (level === 'self') return [];
  return ITEMS.filter((i) => i.pack === 'base');
};

/**
 * פריט סודי אקראי: קודם כאלה שלא היו לאחרונה (recent). כשכל המאגר כבר היה – מכל המאגר.
 * exclude – הפריט הנוכחי ("פריט אחר" לא מחזיר אותו). ברמה 'self' (או רמה לא מוכרת בלי מאגר) – null.
 */
export const pickItem = (level, recent = [], exclude = null) => {
  const all = itemPool(level);
  const pool = all.length > 1 ? all.filter((i) => i.id !== exclude) : all;
  if (!pool.length) return null;
  const seen = new Set(recent);
  const fresh = pool.filter((i) => !seen.has(i.id));
  const from = fresh.length ? fresh : pool;
  return from[Math.floor(Math.random() * from.length)];
};
